a = float(input('Please enter number1 :'))
b = float(input('Please enter number2 :'))
c = input('Please enter an operator (+ – * /) :')

if c == '+':
    result = a + b
    print('Result : ' , result)
elif c == '-':
    result = a - b
    print('Result : ' , result)
elif c == '*':
    result = a * b
    print('Result : ' , result)
elif c == '/':
    result = a / b
    print('Result : ' , result) 
    